"""Generate the tündük SVGs and matching native drawing paths.

Geometry is measured from the reference Kyrgyz-flag tündük (circle fits to its red pixel runs,
max error < 0.4px) and expressed in units of the ring's outer radius R:

  ring         outer 1.000, thickness 0.099
  bands        two mirrored sets of three CONCENTRIC circular arcs; set A is centered at
               (+1.4454, +1.3965) from the ring center (y down) with radii 1.9832 / 2.1896 /
               2.3960, each 0.0928 thick; set B mirrors it about the vertical axis. Bands are
               clipped to the ring, and the innermost pair crosses just below the center, leaving
               the arch at the bottom.

The menu bar glyph is a 16pt circle in the 18pt status item image (24-unit canvas, 1 unit =
0.75pt). At that size the reference's strokes are only ~0.74pt, so the menu bar mark scales
stroke widths by WEIGHT (arc centers, radii and spacing stay exact); the app icon uses 1.0.
"""
from math import atan2, acos, cos, sin, pi, hypot
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

C = 12.0                     # canvas center
R = 16 / 18 * 12             # 16pt circle in the 18pt image -> 10.667 units
RING_T = 0.099               # measured, in units of R
BAND_T = 0.0928
SET_CENTER = (1.4454, 1.3965)
BAND_RADII = (1.9832, 2.1896, 2.3960)
MENU_WEIGHT = 1.35
APP_WEIGHT = 1.0
SAMPLES = 48


def number(value):
    return f"{value:.4f}".rstrip("0").rstrip(".") or "0"


def wrap(a):
    while a <= -pi:
        a += 2 * pi
    while a > pi:
        a -= 2 * pi
    return a


def arc(center, radius, a0, a1, n=SAMPLES):
    return [(center[0] + radius * cos(a0 + (a1 - a0) * k / n),
             center[1] + radius * sin(a0 + (a1 - a0) * k / n)) for k in range(n + 1)]


def crown(weight):
    """Closed polygons (24-unit canvas, y down) for the ring and the six bands."""
    ring_t, band_t = RING_T * weight * R, BAND_T * weight * R
    outer, inner = R, R - ring_t
    clip = R - ring_t / 2          # bands end on the ring's midline, buried in the ring stroke
    o = (C, C)
    polys = [arc(o, outer, 0, 2 * pi, 96), arc(o, inner, 0, 2 * pi, 96)]  # ring (even-odd pair)

    def band(center, radius):
        d = hypot(o[0] - center[0], o[1] - center[1])
        toward = atan2(o[1] - center[1], o[0] - center[0])

        def half_angle(rho):  # band-circle angle span lying inside the clip circle
            return acos((rho * rho + d * d - clip * clip) / (2 * rho * d))

        ro, ri = radius + band_t / 2, radius - band_t / 2
        ao, ai = half_angle(ro), half_angle(ri)
        outer_arc = arc(center, ro, toward - ao, toward + ao)
        inner_arc = arc(center, ri, toward + ai, toward - ai)

        def clip_arc(p, q):
            a0 = atan2(p[1] - o[1], p[0] - o[0])
            a1 = a0 + wrap(atan2(q[1] - o[1], q[0] - o[0]) - a0)
            return arc(o, clip, a0, a1, 8)[1:-1]

        return outer_arc + clip_arc(outer_arc[-1], inner_arc[0]) + inner_arc + clip_arc(inner_arc[-1], outer_arc[0])

    for side in (1, -1):
        center = (C + side * SET_CENTER[0] * R, C + SET_CENTER[1] * R)
        for radius in BAND_RADII:
            polys.append(band(center, radius * R))
    return polys


def svg_d(poly):
    return "M" + " L".join(f"{number(x)} {number(y)}" for x, y in poly) + "Z"


def svg_elements(polys, fill, indent="  "):
    ring = svg_d(polys[0]) + svg_d(polys[1])
    paths = [ring] + [svg_d(p) for p in polys[2:]]
    return "\n".join(f'{indent}<path fill="{fill}" fill-rule="evenodd" d="{d}"/>' for d in paths)


menu = crown(MENU_WEIGHT)
(ROOT / "assets/mark.svg").write_text(f'''<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24">
{svg_elements(menu, '#000')}
</svg>
''')

# App icon: the exact-weight crown in gold on the red tile, ~62% of the tile wide.
APP_SCALE = 24
app_offset = 512 - C * APP_SCALE
(ROOT / "assets/app-icon.svg").write_text(f'''<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <rect x="100" y="100" width="824" height="824" rx="185" fill="#FF0000"/>
  <g transform="translate({number(app_offset)} {number(app_offset)}) scale({APP_SCALE})">
{svg_elements(crown(APP_WEIGHT), '#E0A100', '    ')}
  </g>
</svg>
''')


def swift_lines(poly):
    pts = ", ".join(f"CGPoint(x: {number(x)}, y: {number(y)})" for x, y in poly)
    return f"        path.addLines(between: [{pts}])\n        path.closeSubpath()"


def swift_path(polys):
    body = "\n".join(swift_lines(p) for p in polys)
    return f"    {{\n        let path = CGMutablePath()\n{body}\n        return path\n    }}()"


swift = f'''// Generated by scripts/generate-tunduk.py with assets/mark.svg and assets/app-icon.svg.
// Coordinates use the same 24 × 24 canvas as the SVGs (y down). Do not edit by hand.
import CoreGraphics

enum TundukGeometry {{
    static let crown: [CGPath] = [
{swift_path(menu[:2])},
{",\n".join(swift_path([p]) for p in menu[2:])}
    ]
}}
'''
(ROOT / "Sources/TundukGeometry.swift").write_text(swift)
print("Generated assets/mark.svg, assets/app-icon.svg, and Sources/TundukGeometry.swift")
